from pydantic import BaseModel , Field
from typing import Annotated,Literal
from operator import add
class AgentSchema(BaseModel):
    messages : Annotated[list,add]=Field(..., description="List of messages exchanged between the agent and the user.")
    user_question : str =Field(..., description="The original question asked by the user.")
    curated_question : str=Field(..., description="Curated user question")
    prompt_query_context : str=Field(..., description="A detailed prompt with SQL DB context that will help agent to genarate a query")  
    generated_sql_query : str =Field(..., description="The SQL query generated by the agent based on the user's question and the provided context.")
    is_safe: Literal["yes", "no"] | None = None
    comment: str = ""
    sql_query_execution_result : str =Field(..., description="The result of executing the generated SQL query against the database.")
    final_answer : str =Field(..., description="The final answer provided by the agent to the user based on the SQL query execution result.")

class JudgeSchema(BaseModel):
    answer: Literal["yes", "no"] = Field(..., description="Whether the SQL query is safe to execute.")
    comments: str = Field( ..., description="Explanation of the safety decision.")

class EtlAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(...,description="List of messages to be processed by the ETL agent")

class RouterSchema(BaseModel):
    answer : Literal['sql','etl'] = Field(...,description="Indicates whether the user's question is related to SQL or ETL operations")
    comments : str = Field(...,description="Additional comments or feedback reading the classification")

class DataAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(...,description="List of messages processed")
    route_response : str = Field(...,description="the response from the router")